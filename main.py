# ---------------------------------------------------------
# Logging Utilities
# ---------------------------------------------------------
class Log:
    CYAN = '\033[96m'
    GREEN = '\033[92m'
    YELLOW = '\033[93m'
    RED = '\033[91m'
    RESET = '\033[0m'
    
    @staticmethod
    def agent(name: str):
        print(f"\n{Log.CYAN}{'='*50}\n⚙️  RUNNING NODE: [{name.upper()}]\n{'='*50}{Log.RESET}")

    @staticmethod
    def state_update(key: str, value: str):
        print(f"   {Log.YELLOW}↳ {key}:{Log.RESET} {value[:100]}..." if len(str(value)) > 100 else f"   {Log.YELLOW}↳ {key}:{Log.RESET} {value}")

    @staticmethod
    def success(msg: str):
        print(f"   {Log.GREEN}✓ {msg}{Log.RESET}")
        
    @staticmethod
    def error(msg: str):
        print(f"   {Log.RED}✗ {msg}{Log.RESET}")

# ---------------------------------------------------------
# 1. Define the Graph State Schema
# ---------------------------------------------------------
class AgentState(TypedDict):
    task_description: str
    repo_url: str          # NEW: The GitHub URL to clone
    workspace_path: str    # NEW: The local path where it was cloned
    branch_name: str       # NEW: The feature branch name
    iterations: int
    max_iterations: int
    files: dict
    plan: str
    test_output: str
    status: str
    reviewer_feedback: str

# ---------------------------------------------------------
# 2. Nodes
# --------------------------------

def setup_node(state: dict):
    Log.agent("setup")
    repo_url = state.get("repo_url")
    
    # Generate a unique branch name based on the task
    branch_name = f"devflow/{str(uuid.uuid4())[:8]}"
    
    Log.state_update("GitHub", f"Cloning {repo_url} and creating branch {branch_name}")
    workspace_path = clone_and_branch(repo_url, branch_name)
    
    # NEW: Automatically build the AST vector database for the newly cloned repo
    Log.state_update("Indexer", f"Building AST Vector DB for {workspace_path}")
    build_ast_index(repo_path=workspace_path, persist_dir="chroma_db")
    
    return {
        "workspace_path": workspace_path,
        "branch_name": branch_name
    }

def pr_node(state: dict):
    Log.agent("github_pr")
    repo_url = state.get("repo_url")
    workspace_path = state.get("workspace_path")
    branch_name = state.get("branch_name")
    task = state.get("task_description")
    
    # Extract just the "username/repo" format for PyGithub
    repo_name = "/".join(repo_url.replace(".git", "").split("/")[-2:])
    
    Log.state_update("GitHub", f"Pushing branch and creating PR for {repo_name}")
    pr_url = create_pull_request(
        repo_name=repo_name,
        branch_name=branch_name,
        title=f"DevFlow: {task[:50]}...",
        body=f"Automated changes generated by DevFlow.\n\n**Task:** {task}"
    )
    
    Log.state_update("Success", f"Pull Request opened: {pr_url}")
    return {"status": "completed"}


def human_code_review_node(state: dict):
    Log.agent("human_code_review")
    
    # Stage 1: Pause and ask for code feedback
    feedback = interrupt({
        "stage": "code_review",
        "question": "AI coding complete. Do you approve these changes or want to request edits?",
        "files": state.get("files", {})
    })
    
    # If you reply with anything other than "approve", it routes back to the planner
    if feedback.strip().lower() == "approve":
        Log.success("Human approved the code modifications.")
        return {"status": "code_approved"}
    else:
        Log.error(f"Human requested edits: {feedback}")
        return {
            "status": "in_progress", 
            "reviewer_feedback": feedback, 
            "iterations": state.get("iterations", 0) + 1
        }

def human_pr_approval_node(state: dict):
    Log.agent("human_pr_approval")
    
    # Stage 2: Final gate before touching the GitHub API
    feedback = interrupt({
        "stage": "pr_approval",
        "question": f"Ready to push branch '{state.get('branch_name')}' and open a PR on GitHub. Proceed?",
        "files": state.get("files", {}) # Included so server.py doesn't throw a KeyError
    })
    
    if feedback.strip().lower() == "approve":
        Log.success("Human authorized GitHub PR creation.")
        return {"status": "pr_approved"}
    else:
        Log.error("Human aborted the PR process.")
        return {"status": "pr_aborted"}


# --------------- Reader NODE AST Aware RAG Architecture ---------------
def reader_node(state: dict):
    Log.agent("reader")
    task = state.get("task_description", "")
    
    Log.state_update("Querying DB", "Searching AST-aware vector store for logical structures...")
    
    
    if not os.path.exists("chroma_db"):
        Log.error("chroma_db not found. Did you run ast_indexer.py?")
        return {"files": {}}
        
    vectorstore = Chroma(persist_directory="chroma_db", 
        embedding_function=global_embeddings)
    
    # Retrieve the top 5 most relevant structural chunks
    retrieved_docs = vectorstore.similarity_search(task, k=5)
    
    relevant_filenames = set()
    retrieved_structures = []
    
    for doc in retrieved_docs:
        filename = doc.metadata.get("filename")
        node_type = doc.metadata.get("node_type", "Unknown")
        node_name = doc.metadata.get("node_name", "Unknown")
        
        if filename:
            relevant_filenames.add(filename)
            # We now know EXACTLY what logical block triggered the match
            retrieved_structures.append(f"[{node_type}: {node_name}]")
            
    if not relevant_filenames:
        Log.error("No relevant structures found in the vector database.")
        return {"files": {}}
        
    # Log the specific architecture it found, removing duplicates
    unique_structures = list(dict.fromkeys(retrieved_structures))
    Log.state_update("AST Match", ", ".join(unique_structures))
    
    # Load the specific files those structures belong to
    repo_path = state.get("workspace_path", "dummy_repo")
    loaded_files = {}
    
    for filename in relevant_filenames:
        filepath = os.path.join(repo_path, filename)
        if os.path.exists(filepath):
            with open(filepath, "r", encoding="utf-8") as f:
                loaded_files[filename] = f.read()
                
    Log.state_update("Loaded Files", f"Injected {len(loaded_files)} file(s) into state.")
    return {"files": loaded_files}

def tester_node(state: dict):
    Log.agent("tester")
    files = state.get("files", {})
    if not files:
        Log.error("No files generated to test.")
        return {"test_output": "No files generated to test.", "status": "failed"}

    repo_path = state.get("workspace_path", "dummy_repo")
    os.makedirs(repo_path, exist_ok=True)
    test_filepath = ""
    
    for filename, code_content in files.items():
        filepath = os.path.join(repo_path, filename)
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(code_content)
        if filename.endswith(".py"):
            test_filepath = filepath
            
    try:
        result = subprocess.run([sys.executable, test_filepath], capture_output=True, text=True, timeout=5)
        if result.returncode == 0:
            Log.success(f"Execution passed for {filename}")
            return {"test_output": f"Success. Output:\n{result.stdout}", "status": "success"}
        else:
            Log.error(f"Execution crashed. Traceback sent to Coder.")
            return {"test_output": f"Error:\n{result.stderr}", "status": "failed"}
            
    except subprocess.TimeoutExpired:
        Log.error("Execution timed out (infinite loop detected).")
        return {"test_output": "Error: Script execution timed out.", "status": "failed"}


