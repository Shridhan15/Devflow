workflow = StateGraph(AgentState)

# Register all nodes
workflow.add_node("setup", setup_node)
workflow.add_node("reader", reader_node)
workflow.add_node("planner", planner_node)
workflow.add_node("coder", coder_node)
workflow.add_node("tester", tester_node)
workflow.add_node("reviewer", reviewer_node)
workflow.add_node("human_code_review", human_code_review_node)
workflow.add_node("human_pr_approval", human_pr_approval_node)
workflow.add_node("pr_node", pr_node)

# Standard AI pipeline
workflow.set_entry_point("setup")
workflow.add_edge("setup", "reader")
workflow.add_edge("reader", "planner")
workflow.add_edge("planner", "coder")
workflow.add_edge("coder", "tester")
workflow.add_edge("tester", "reviewer")

# ----------------- ROUTING LOGIC -----------------
def ai_review_routing(state: dict):
    """Route based on AI Reviewer's decision."""
    status = state.get("status", "").lower()
    
    # Catch any variation of approval your AI might be outputting
    if status in ["approved", "pass", "passed", "success"] or state.get("iterations", 0) >= state.get("max_iterations", 3):
        return "human_code_review"
    
    return "planner"

def human_code_routing(state: dict):
    """Route based on human's Stage 1 code review."""
    if state.get("status") == "code_approved":
        return "human_pr_approval"
    return "planner"

def human_pr_routing(state: dict):
    """Route based on human's Stage 2 PR authorization."""
    if state.get("status") == "pr_approved":
        return "pr_node"
    return END

# Wire the conditional routers
workflow.add_conditional_edges("reviewer", ai_review_routing)
workflow.add_conditional_edges("human_code_review", human_code_routing)
workflow.add_conditional_edges("human_pr_approval", human_pr_routing)
workflow.add_edge("pr_node", END)

# Compile with persistent memory
conn = sqlite3.connect("devflow_state.sqlite", check_same_thread=False)
memory = SqliteSaver(conn)
app = workflow.compile(checkpointer=memory)
# ---------------------------------------------------------
# 5. Execution Loop
# ---------------------------------------------------------
if __name__ == "__main__":
    print(f"\n{Log.GREEN}🚀 Welcome to DevFlow MVP{Log.RESET}")
    user_task = input("What would you like me to build or change?\n> ")
    
    initial_state = {
        "task_description": user_task,
        "iterations": 0,
        "max_iterations": 3,
        "files": {},
        "plan": "",
        "test_output": "",
        "status": "in_progress",
        "reviewer_feedback": ""
    }
    
    # Thread ID tracks the memory state
    thread = {"configurable": {"thread_id": "session_1"}}
    
    # We use a variable for the input so we can easily swap between 
    # initial_state (first run) and Command(resume=...) (subsequent runs)
    stream_input = initial_state
    
    # NEW: A continuous loop to handle multiple human rejection cycles
    while True:
        # Run the graph until it finishes OR hits an interrupt
        for output in app.stream(stream_input, thread):
            pass
            
        # Detect what state the graph is in now
        current_state = app.get_state(thread)
        
        # If the graph paused for an interrupt, ask the user
        if current_state.tasks and current_state.tasks[0].interrupts:
            interrupt_data = current_state.tasks[0].interrupts[0].value
            
            print(f"\n{Log.YELLOW}{'='*50}")
            print(f"⏸️  {interrupt_data['question']}")
            print(f"{'='*50}{Log.RESET}")
            
            for filename, content in interrupt_data["files"].items():
                print(f"\n{Log.CYAN}--- Proposed {filename} ---{Log.RESET}")
                print(content)
                
            print(f"\n{Log.YELLOW}{'='*50}{Log.RESET}")
            user_input = input("> ")
            
            # Set the input for the next loop iteration to resume the graph
            stream_input = Command(resume=user_input)
            
        else:
            # No interrupts found, meaning the graph reached the END node
            break

    print(f"\n{Log.GREEN}✅ Run complete. Check the 'dummy_repo' directory for the final code.{Log.RESET}")